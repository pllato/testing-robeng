def main():
    data = json.load(open(SRC, encoding='utf-8'))
    needed = set()
    for L in data['lessons']:
        for w in L.get('words', []):
            needed.add(w.lower().strip())
        for wa in L.get('media', {}).get('word_assets', []):
            if wa.get('word'):
                needed.add(wa['word'].lower().strip())

    missing = sorted(w for w in needed if w not in TR)
    if missing:
        print(f"⚠️  {len(missing)} words missing from dictionary:")
        for w in missing[:30]:
            print(f"   - {w!r}")
        if len(missing) > 30:
            print(f"   …and {len(missing)-30} more")

    out = {w: TR[w] for w in sorted(needed) if w in TR}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump({"version": 1, "translations": out}, f, ensure_ascii=False, indent=2)
    print(f"✓ Wrote {len(out)} translations to {OUT}")

if __name__ == '__main__':
    main()
